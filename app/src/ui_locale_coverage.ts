export interface UiLocaleCoverage {
  code: string
  dir: TranslationLanguage['dir']
  translated: number
  total: number
  missing: readonly string[]
  fallback: 'ar'
}

export function uiLocaleCoverageReport(
  languages: readonly TranslationLanguage[] = TRANSLATION_LANGUAGES,
): readonly UiLocaleCoverage[] {
  return languages.map(language => {
    const catalog = UI_TRANSLATIONS[language.code] ?? {}
    const missing = CORE_UI_LABELS.filter(label => !catalog[label])
    return {
      code: language.code,
      dir: language.dir,
      translated: CORE_UI_LABELS.length - missing.length,
      total: CORE_UI_LABELS.length,
      missing,
      fallback: 'ar',
    }
  })
}

